// ==================== 标签归组与描述（分层 → 平面）====================
// 把一个作家/一个标签集按 STYLE_DIMENSIONS 归组为「维度 → 标签数组」。
export function groupTagsByDim(tags = []) {
  const dimOf = new Map()
  for (const [dim, list] of Object.entries(STYLE_DIMENSIONS)) {
    for (const t of list) dimOf.set(t, dim)
  }
  const groups = {}
  for (const t of tags) {
    const dim = dimOf.get(t)
    if (!dim) continue
    ;(groups[dim] ||= []).push(t)
  }
  return groups
}

// 生成给模型看的【分层】标签描述：按维度排布，未命中的维度省略。
// 例：汪曾祺 → 「句法节奏[短句] 语言质地[白描] 题材[市井] 情感[冲淡] 意象[市井烟火] 结构[散文化]」
export function tagsToHierarchical(tags = []) {
  const groups = groupTagsByDim(tags)
  const dimOrder = Object.keys(STYLE_DIMENSIONS)
  const dimShort = { 句法节奏: '句法', 语言质地: '语言', 题材内容: '题材', 情感基调: '情感', 意象系统: '意象', 叙事结构: '结构' }
  return dimOrder
    .filter((d) => groups[d] && groups[d].length)
    .map((d) => `${dimShort[d]}:[${groups[d].join('/')}]`)
    .join(' ')
}

// 两位作家标签集的分层相似度：命中同维度内「对立极」扣分、共享加分、关联标签（同维度相邻）部分加分。
// 返回 { score, shared, opposed, related, dims }；score 用于海选排序。
export function hierarchicalSimilarity(tagsA = [], tagsB = []) {
  const dimOf = new Map()
  for (const [dim, list] of Object.entries(STYLE_DIMENSIONS)) {
    for (const t of list) dimOf.set(t, dim)
  }
  const setA = new Set(tagsA)
  const setB = new Set(tagsB)
  const shared = []
  const opposed = []
  const related = []
  for (const t of tagsA) {
    if (setB.has(t)) {
      shared.push(t)
    } else {
      const opp = (TAG_OPPOSITES[t] || []).filter((o) => setB.has(o))
      if (opp.length) {
        opposed.push(`${t}↔${opp[0]}`)
        continue
      }
      // 同维度内关联标签：一方有 A、另一方有 B（同维度且互为近邻）→ 部分相似，加分 0.5
      const rel = (TAG_AFFINITY[t] || []).filter((o) => setB.has(o))
      if (rel.length) related.push(`${t}~${rel[0]}`)
    }
  }
  // 同维度共享权重更高：先按"命中几个维度"奖励广度，再按共享数奖励深度。
  // 关联标签计半分（0.5），对立极扣分（1.5）。
  const sharedDims = new Set(shared.map((t) => dimOf.get(t))).size
  const score = shared.length * 1 + sharedDims * 0.5 + related.length * 0.5 - opposed.length * 1.5
  return { score, shared, opposed, related, dims: sharedDims }
}
